let currentLanguage = 'kz';
function setLanguage(language) {
  language = language === 'ru' ? 'ru' : 'kz';
  currentLanguage = language;
  const copy = language === 'ru' ? russianCopy : kazakhCopy;
  Object.entries(copy).forEach(([selector, value]) => {
    const element = document.querySelector(selector);
    if (element) element.innerHTML = value;
  });

  const meta = metadata[language];
  document.documentElement.lang = meta.lang;
  document.title = meta.title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', meta.description);

  Object.entries(ariaLabels[language]).forEach(([selector, value]) => {
    document.querySelector(selector)?.setAttribute('aria-label', value);
  });

  document.querySelectorAll('a[href^="https://wa.me/77479896274"]').forEach((link) => {
    link.href = whatsappLinks[language];
    link.setAttribute('aria-label', language === 'ru' ? 'Запросить трёхдневный тест в WhatsApp' : 'WhatsApp арқылы үш күндік сынаққа өтінім беру');
  });

  document.querySelectorAll('[data-language]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  document.dispatchEvent(new CustomEvent('proposal:language', { detail: language }));
}

document.querySelectorAll('[data-language]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

setLanguage('kz');


const revealItems = document.querySelectorAll('.reveal');

if ('IntersectionObserver' in window && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });

  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add('is-visible'));
}
